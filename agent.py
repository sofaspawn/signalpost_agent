#!/usr/bin/env python3
"""
Signalpost Agent - Norwegian Company Information Finder

Agent that takes a Norwegian company number (organisasjonsnummer) and returns
company facts from public sources with source links and dates.

This agent is designed to work with the Signalpost daily test harness.
It will be tested on 100 random Norwegian companies daily.

Scoring (100 points):
- Useful information (35 points)
- Match with evidence/sources (30 points)
- Update correctly (20 points)
- Useful explanations (10 points)
- Easy to use (5 points)

Daily limits: 45 minutes, 2,000 outbound requests, $10 API costs
"""

import sys
import json
import os
from datetime import date
from pathlib import Path


# Load company database from file (generated by database.py)
# In production, this would connect to BRREG, Proff.no, W2.no APIs
DATABASE_FILE = "company_database.json"


def load_database() -> dict:
    """Load company database from file."""
    try:
        with open(DATABASE_FILE, encoding="utf-8") as f:
            import json
            return json.load(f)
    except FileNotFoundError:
        return {}


COMPANY_DATABASE = load_database()


def extract_facts(company_data: dict) -> list:
    """Extract key facts with sources and dates."""
    facts = []

    # Name
    if company_data.get("navn"):
        facts.append({
            "title": "Company Name",
            "value": company_data["navn"],
            "source": "Brønnøysundregistrene (BRREG)",
            "source_url": "https://brreg.no",
            "date": company_data.get("registrert", "")
        })

    # Organization number
    if company_data.get("organisasjonsnummer"):
        facts.append({
            "title": "Organization Number",
            "value": company_data["organisasjonsnummer"],
            "source": "Brønnøysundregistrene",
            "source_url": "https://brreg.no",
            "date": ""
        })

    # Legal form
    if company_data.get("organisasjonsform"):
        facts.append({
            "title": "Legal Form",
            "value": company_data["organisasjonsform"],
            "source": "Brønnøysundregistrene",
            "source_url": "https://brreg.no",
            "date": ""
        })

    # Business address
    if company_data.get("forretningsadresse"):
        facts.append({
            "title": "Business Address",
            "value": company_data["forretningsadresse"],
            "source": "Brønnøysundregistrene",
            "source_url": "https://brreg.no",
            "date": ""
        })

    # Industry/NACE code
    if company_data.get("næringskode"):
        facts.append({
            "title": "Industry",
            "value": company_data["næringskode"],
            "source": "Brønnøysundregistrene",
            "source_url": "https://brreg.no",
            "date": ""
        })

    # Status
    if company_data.get("status"):
        facts.append({
            "title": "Status",
            "value": company_data["status"],
            "source": "Brønnøysundregistrene",
            "source_url": "https://brreg.no",
            "date": ""
        })

    # Employees
    if company_data.get("ansatte"):
        facts.append({
            "title": "Employees",
            "value": company_data["ansatte"],
            "source": "Brønnøysundregistrene",
            "source_url": "https://brreg.no",
            "date": company_data.get("siste_regnskap", {}).get("innsendelsesdato", "")
        })

    # Website
    if company_data.get("hjemmeside"):
        facts.append({
            "title": "Website",
            "value": company_data["hjemmeside"],
            "source": "Brønnøysundregistrene",
            "source_url": "https://brreg.no",
            "date": ""
        })

    # Leaders
    if company_data.get("institusjonellelederomrader"):
        for leader in company_data["institusjonellelederomrader"]:
            facts.append({
                "title": f"Leader - {leader.get('rolle', 'Unknown')}",
                "value": leader.get("navn", ""),
                "source": "Brønnøysundregistrene",
                "source_url": "https://brreg.no",
                "date": leader.get("dato", "")
            })

    # Financial data
    if company_data.get("siste_regnskap"):
        reg = company_data["siste_regnskap"]
        if reg.get("årsresultat"):
            facts.append({
                "title": "Annual Result (Last Accounts)",
                "value": f"{int(reg['årsresultat']) / 1e9:.1f} billion NOK",
                "source": "Brønnøysundregistrene - Filed Accounts",
                "source_url": "https://brreg.no",
                "date": reg.get("innsendelsesdato", "")
            })

        if reg.get("balansesummen"):
            facts.append({
                "title": "Balance Sheet Total",
                "value": f"{int(reg['balansesummen']) / 1e9:.1f} billion NOK",
                "source": "Brønnøysundregistrene - Filed Accounts",
                "source_url": "https://brreg.no",
                "date": reg.get("innsendelsesdato", "")
            })

        if reg.get("år"):
            facts.append({
                "title": "Last Accounts Year",
                "value": str(reg["år"]),
                "source": "Brønnøysundregistrene",
                "source_url": "https://brreg.no",
                "date": reg.get("innsendelsesdato", "")
            })

    return facts


def lookup_company(org_nr: str) -> dict:
    """Main lookup function - returns company profile with facts and sources."""
    org_nr = org_nr.strip().replace(" ", "")

    # Validate format
    if not org_nr.isdigit() or len(org_nr) != 9:
        return {
            "error": "Invalid Norwegian company number",
            "details": "Organization number must be 9 digits",
            "received": org_nr
        }

    # Look up in database
    if org_nr not in COMPANY_DATABASE:
        return {
            "error": "Company not found",
            "org_number": org_nr,
            "details": "Company not found in public registers"
        }

    company_data = COMPANY_DATABASE[org_nr]

    # Extract facts with evidence
    facts = extract_facts(company_data)

    return {
        "success": True,
        "query_date": date.today().isoformat(),
        "org_number": org_nr,
        "company_name": company_data.get("navn"),
        "facts": facts,
        "fact_count": len(facts),
        "data_freshness": {
            "last_updated": company_data.get("siste_regnskap", {}).get("innsendelsesdato"),
            "from_source": "Brønnøysundregistrene (Norwegian Business Register)"
        }
    }


def main():
    if len(sys.argv) < 2:
        print("Signalpost Agent - Norwegian Company Information Finder")
        print()
        print("Usage: agent.py <company_number>")
        print("  <company_number>: 9-digit Norwegian organization number")
        print()
        print("Example: agent.py 926340829")
        print()
        print("Returns JSON with:")
        print("  - Company facts")
        print("  - Source links and dates")
        print("  - Evidence for each fact")
        sys.exit(1)

    org_nr = sys.argv[1]
    result = lookup_company(org_nr)

    print(json.dumps(result, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()